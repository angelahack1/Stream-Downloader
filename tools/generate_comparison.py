_CS_DECL = re.compile(r"^(?: {0}| {4})(?:\[[^\]]*\]\s*)?(?:(?:public|private|internal|protected|static|sealed|partial|override|async|readonly|const|required|abstract|virtual|extern)\s+)+(?P<rest>\S.*)$")
_TOOL_NAME = re.compile(r'Name = "(?P<name>[a-z_]+)"')


def members(path: str, lines: list[str]) -> list[tuple[str, str]]:
    """The enclosing (type, member) of every line: C# type and method/property/field/tool, Python
    def/class, PowerShell function, Markdown heading. Comments and attributes belong to the member
    they introduce."""
    owners: list[tuple[str, str]] = []
    current_type = current = ""
    suffix = Path(path).suffix.lower()
    pending_tool = in_tool = False
    starts: list[int] = []
    for index, line in enumerate(lines):
        if suffix == ".cs":
            if re.match(r"^ {4}\[McpServerTool\(", line):
                pending_tool, in_tool, current = True, False, "(tool)"
                starts.append(index)
            elif pending_tool and _TOOL_NAME.search(line):
                current, pending_tool, in_tool = _TOOL_NAME.search(line).group("name"), False, True
            else:
                match = _CS_DECL.match(line)
                if match and not pending_tool and not in_tool and not line.lstrip().startswith("["):
                    rest = match.group("rest")
                    kind = re.match(r"(?:class|record|struct|enum|interface)\s+(\w+)", rest)
                    if kind and not line.startswith(" "):
                        current_type, current = kind.group(1), ""
                    elif kind:
                        current = kind.group(1)
                    else:
                        head = re.split(r"[({=;]", rest, maxsplit=1)[0]
                        names = re.findall(r"[A-Za-z_][A-Za-z0-9_]*", head)
                        if names:
                            current = names[-1]
                    starts.append(index)
        elif suffix == ".py":
            match = re.match(r"^\s*(?:async\s+)?(?:def|class)\s+(\w+)", line)
            if match:
                current = match.group(1)
        elif suffix == ".ps1":
            match = re.match(r"^\s*function\s+([\w-]+)", line, re.IGNORECASE)
            if match:
                current = match.group(1)
        elif suffix == ".md":
            match = re.match(r"^#{1,4}\s+(.*)$", line)
            if match:
                current = match.group(1).strip()
        owners.append((current_type, current))
    for start in starts:  # doc comments, attributes and the blank line before a member are its own
        k = start - 1
        while k >= 0 and (not lines[k].strip() or lines[k].strip().startswith(("//", "[", "/*", "*"))):
            owners[k] = owners[start]
            k -= 1
    return owners


def note_for(keys: list[tuple[str, str]], pair: Pair) -> str:
    """Member note, then the enclosing type's note, then the file's own reason."""
    for file_key, (type_name, member) in keys:
        if member and (file_key, member) in MEMBER_NOTES:
            return MEMBER_NOTES[(file_key, member)]
    for file_key, (type_name, member) in keys:
        if type_name and (file_key, "type:" + type_name) in MEMBER_NOTES:
            return MEMBER_NOTES[(file_key, "type:" + type_name)]
    return pair.note


# ============================================================================ alignment
def normalize(line: str) -> str:
    for old, new in RENAMES:
        line = line.replace(old, new)
    return line


def similarity(left: str, right: str) -> float:
    if left == right:
        return 1.0
    if not left or not right:
        return 0.0
    matcher = difflib.SequenceMatcher(None, left, right, autojunk=False)
    if matcher.real_quick_ratio() < 0.5 or matcher.quick_ratio() < 0.5:
        return 0.0
    return matcher.ratio()


def pair_block(left: list[str], right: list[str], i0: int, j0: int) -> list[tuple[int | None, int | None]]:
    """Order-preserving pairing of a changed block that maximises total line similarity."""
    n, m = len(left), len(right)
    if n * m > 400_000:
        return [(i0 + i, None) for i in range(n)] + [(None, j0 + j) for j in range(m)]
    score = [[0.0] * (m + 1) for _ in range(n + 1)]
    for i in range(n - 1, -1, -1):
        for j in range(m - 1, -1, -1):
            best = max(score[i + 1][j], score[i][j + 1])
            ratio = similarity(left[i], right[j])
            if ratio >= 0.5:
                best = max(best, score[i + 1][j + 1] + ratio)
            score[i][j] = best
    rows: list[tuple[int | None, int | None]] = []
    i = j = 0
    while i < n and j < m:
        ratio = similarity(left[i], right[j])
        if ratio >= 0.5 and abs(score[i][j] - (score[i + 1][j + 1] + ratio)) < 1e-9:
            rows.append((i0 + i, j0 + j))
            i, j = i + 1, j + 1
        elif score[i + 1][j] >= score[i][j + 1]:
            rows.append((i0 + i, None))
            i += 1
        else:
            rows.append((None, j0 + j))
            j += 1
    rows += [(i0 + k, None) for k in range(i, n)] + [(None, j0 + k) for k in range(j, m)]
    return rows


def align(idm: list[str], sd: list[str]) -> list[tuple[int | None, int | None]]:
    a = [normalize(line).strip() for line in idm]
    b = [line.strip() for line in sd]
    rows: list[tuple[int | None, int | None]] = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "equal":
            rows += list(zip(range(i1, i2), range(j1, j2)))
        elif tag == "delete":
            rows += [(i, None) for i in range(i1, i2)]
        elif tag == "insert":
            rows += [(None, j) for j in range(j1, j2)]
        else:
            rows += pair_block(a[i1:i2], b[j1:j2], i1, j1)
    return rows


STATUS_GLYPH = {"identical": "=", "renamed": "≈", "modified": "✎", "removed": "−", "added": "+"}


@dataclass
class Row:
    idm_no: int | None
    idm_text: str | None
    status: str
    sd_no: int | None
    sd_text: str | None
    note: str


def compare(pair: Pair, idm_root: Path) -> tuple[list[Row], dict]:
    idm_lines = read_lines(idm_root / pair.idm) if pair.idm else []
    sd_lines = read_lines(SD_ROOT / pair.sd) if pair.sd else []
    idm_owner = members(pair.idm or "", idm_lines)
    sd_owner = members(pair.sd or "", sd_lines)
    idm_key = Path(pair.idm).name if pair.idm else ""
    sd_key = Path(pair.sd).name if pair.sd else ""
    rows: list[Row] = []
    for i, j in align(idm_lines, sd_lines):
        left = idm_lines[i] if i is not None else None
        right = sd_lines[j] if j is not None else None
        if left is not None and right is not None:
            status = "identical" if left == right else "renamed" if normalize(left) == right else "modified"
        else:
            status = "removed" if right is None else "added"
        note = ""
        if status == "renamed":
            note = "rename"
        elif status != "identical":
            keys = []
            if i is not None:
                keys += [(idm_key, idm_owner[i]), (sd_key, idm_owner[i])]
            if j is not None:
                keys += [(sd_key, sd_owner[j]), (idm_key, sd_owner[j])]
            note = note_for(keys, pair)
        rows.append(Row(None if i is None else i + 1, left, status, None if j is None else j + 1, right, note))
    counts = {key: sum(1 for r in rows if r.status == key) for key in STATUS_GLYPH}
    counts["idmLines"], counts["sdLines"] = len(idm_lines), len(sd_lines)
    return rows, counts


# ============================================================================ rendering
_MD_ESCAPES = {"|": "&#124;", "*": "&#42;", "_": "&#95;", "`": "&#96;", "[": "&#91;", "]": "&#93;",
               "~": "&#126;", "$": "&#36;", "\\": "&#92;", "#": "&#35;", "!": "&#33;", "{": "&#123;", "}": "&#125;"}


def md_code(text: str | None) -> str:
    if text is None:
        return ""
    escaped = html.escape(text, quote=False)
    escaped = "".join(_MD_ESCAPES.get(ch, ch) for ch in escaped).replace("\t", "&#9;")
    leading = len(escaped) - len(escaped.lstrip(" "))
    escaped = "&nbsp;" * leading + escaped[leading:]
    escaped = re.sub(r"  +", lambda m: "&nbsp;" * len(m.group(0)), escaped)
    return f"<code>{escaped}</code>"


def md_text(text: str) -> str:
    return text.replace("|", "&#124;")


def fingerprint(entries: list[tuple[str, str]]) -> str:
    material = "\n".join(f"{name}\t{digest}" for name, digest in entries)
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


def build(idm_root: Path) -> tuple[str, str, dict]:
    if not idm_root.is_dir():
        raise SystemExit(f"IDM_SOURCE_MISSING: {idm_root} does not exist (set --idm or IDM_ROOT).")
    idm_files = managed_files(idm_root, MANAGED_FOLDERS_IDM, set())
    sd_files = managed_files(SD_ROOT, MANAGED_FOLDERS_SD, set(OUTPUTS))
    pairs = list(PAIRS)
    known_sd = {p.sd for p in pairs if p.sd} | {s for _, s, _ in NOT_LINE_COMPARED if s}
    for extra in sd_files:
        if extra not in known_sd:
            folder = extra.split("/", 1)[0] if "/" in extra else "root"
            pairs.append(Pair(None, extra, "New in Stream-Downloader", ADDED_NOTES.get(extra, f"New {folder} file of Stream-Downloader.")))
    accounted_idm = {p.idm for p in pairs if p.idm} | {i for i, _, _ in NOT_LINE_COMPARED if i}
    unaccounted = [f for f in idm_files if f not in accounted_idm]
    missing_idm = [p.idm for p in pairs if p.idm and not (idm_root / p.idm).is_file()]
    missing_sd = [p.sd for p in pairs if p.sd and not (SD_ROOT / p.sd).is_file()]
    if unaccounted or missing_idm or missing_sd:
        raise SystemExit("UNACCOUNTED FILES - the comparison would be incomplete:\n"
                         + "\n".join([f"  IDM file not mapped: {f}" for f in unaccounted]
                                     + [f"  IDM file missing: {f}" for f in missing_idm]
                                     + [f"  Stream-Downloader file missing: {f}" for f in missing_sd]))
    for path, _, _ in NOT_LINE_COMPARED:
        if path and path.endswith("appsettings.json") and sha256(idm_root / path) != sha256(idm_root / "src/IdmMcp.McpHost/appsettings.json"):
            raise SystemExit("artifacts/local/appsettings.json no longer equals the source copy; compare it line by line.")
    sections, totals = [], {key: 0 for key in [*STATUS_GLYPH, "idmLines", "sdLines"]}
    for number, pair in enumerate(pairs, 1):
        rows, counts = compare(pair, idm_root)
        for key in totals:
            totals[key] += counts[key]
        sections.append((number, pair, rows, counts))
    inputs = [("idm:" + f, sha256(idm_root / f)) for f in idm_files] + [("sd:" + f, sha256(SD_ROOT / f)) for f in sd_files]
    meta = dict(fingerprint=fingerprint(inputs), idmFiles=len(idm_files), sdFiles=len(sd_files), totals=totals,
                evidence={name: sum(1 for p in (idm_root / name).rglob("*") if p.is_file()) for name in EVIDENCE_FOLDERS_IDM if (idm_root / name).is_dir()})
    return render_md(sections, meta, idm_root, idm_files), render_html(sections, meta, idm_root), meta


