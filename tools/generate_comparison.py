def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--idm", type=Path, default=DEFAULT_IDM_ROOT)
    parser.add_argument("--check", action="store_true", help="fail if COMPARISON.md/html are stale")
    args = parser.parse_args()
    markdown, page, meta = build(args.idm)
    targets = {"COMPARISON.md": markdown, "COMPARISON.html": page}
    if args.check:
        stale = [name for name, text in targets.items()
                 if not (SD_ROOT / name).is_file() or (SD_ROOT / name).read_text(encoding="utf-8") != text]
        print("STALE: " + ", ".join(stale) if stale else "CURRENT: both documents match their inputs.")
        return 1 if stale else 0
    for name, text in targets.items():
        (SD_ROOT / name).write_text(text, encoding="utf-8", newline="\n")
    t = meta["totals"]
    print(json.dumps(dict(written=list(targets), fingerprint=meta["fingerprint"], totals=t), indent=2))
    return 0


