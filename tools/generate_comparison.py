# ============================================================================ reading
def read_lines(path: Path) -> list[str]:
    text = path.read_bytes().decode("utf-8-sig")
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return [line[:-1] if line.endswith("\r") else line for line in lines]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def is_text(path: Path) -> bool:
    try:
        path.read_bytes().decode("utf-8-sig")
        return b"\x00" not in path.read_bytes()[:8192]
    except UnicodeDecodeError:
        return False


def managed_files(root: Path, folders: tuple[str, ...], exclude: set[str]) -> list[str]:
    found = [p.name for p in root.iterdir() if p.is_file() and p.name not in exclude]
    for folder in folders:
        base = root / folder
        if base.is_dir():
            for path in base.rglob("*"):
                relative = path.relative_to(root)
                if path.is_file() and not (set(relative.parts) & SKIP_PARTS):
                    found.append(relative.as_posix())
    return sorted(found, key=str.lower)


